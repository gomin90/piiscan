#!/usr/bin/env python3
"""Build requirements-lock.txt from the actual wheelhouse contents.

    python tools/make_wheelhouse_lock.py

The lock file is a factual record of what is shipped: wheel filename, byte size
and SHA256. It is not a pip-installable requirement file (that is
requirements-win.txt); it exists so an air-gapped operator can prove that the
wheels on the target machine are the ones the bundle was built with.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WHEEL_DIR = ROOT / "vendor" / "wheels"

HEADER = """# Pinned dependency set for the Windows offline wheelhouse (vendor/wheels).
# Generated by:  python tools/make_wheelhouse_lock.py
# Install offline:  python -m pip install --no-index --find-links vendor/wheels -r requirements/requirements-win.txt
#
# Wheels were downloaded for win_amd64 / CPython 3.12 on a macOS dev box.
# They have NOT been installed or executed on Windows yet - that is the user's step.
# Licences: see docs/THIRD-PARTY-NOTICES.md
"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Wheelhouse lock file")
    parser.add_argument("--output", default="requirements/requirements-lock.txt")
    parser.add_argument("--json", default="", help="optional JSON sidecar with the same data")
    args = parser.parse_args()

    wheels = sorted(WHEEL_DIR.glob("*.whl"))
    if not wheels:
        print(f"[fail] no wheels in {WHEEL_DIR}")
        return 1

    lines = [HEADER]
    records = []
    for wheel in wheels:
        digest = hashlib.sha256(wheel.read_bytes()).hexdigest()
        size = wheel.stat().st_size
        lines.append(f"{wheel.name}  {size}  sha256:{digest}")
        records.append({"wheel": wheel.name, "size": size, "sha256": digest})

    out = ROOT / args.output
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"[ok] {out}: {len(wheels)} wheels, {sum(r['size'] for r in records) / 1024**2:.1f} MB")

    if args.json:
        sidecar = ROOT / args.json
        sidecar.parent.mkdir(parents=True, exist_ok=True)
        sidecar.write_text(json.dumps({"generated": date.today().isoformat(), "wheels": records},
                                      indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"[ok] {sidecar}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
